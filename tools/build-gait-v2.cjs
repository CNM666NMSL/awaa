'use strict';
// Slice generated complete gait cycles with one constant scale per cycle.
const fs=require('node:fs'),path=require('node:path');
const {ROOT,IDENTITIES,context,files,sharp,readSheet,metrics,removeAdjacentFragments}=require('./expand-animation-frames.cjs');
const OUT=path.join(ROOT,'assets/chars/gait-v2');
async function slice(file,rowsExpected){
 const {data,info,rows:detected}=await readSheet(file);
 const rows=rowsExpected===2?Array.from({length:2},(_,i)=>[Math.floor(i*info.height/2),Math.floor((i+1)*info.height/2)]):detected;
 if(rows.length!==rowsExpected)throw Error(`${file}: expected ${rowsExpected} rows, found ${rows.length}`);
 const cells=[];
 for(let r=0;r<rows.length;r++){
  const top=r?Math.floor((rows[r-1][1]+rows[r][0])/2):0,bottom=r===rows.length-1?info.height:Math.floor((rows[r][1]+rows[r+1][0])/2);
  for(let col=0;col<5;col++){
   const left=Math.floor(col*info.width/5),right=Math.floor((col+1)*info.width/5);
   const raw=await sharp(data,{raw:info}).extract({left,top,width:right-left,height:bottom-top}).raw().toBuffer();
   removeAdjacentFragments(raw,right-left,bottom-top);
   cells.push({data:raw,width:right-left,height:bottom-top,row:r,column:col,m:metrics(raw,right-left,bottom-top)});
  }
 }
 return cells;
}
function headX(cell){const {data,width,m}=cell;let sum=0,n=0;for(let y=m.head;y<m.head+m.height*.17;y++)for(let x=0;x<width;x++)if(data[(y*width+x)*4+3]>140){sum+=x;n++;}return sum/n;}
async function main(){
 const jobs=JSON.parse(fs.readFileSync(path.join(OUT,'generation-jobs.json'))),walkJobs=JSON.parse(fs.readFileSync(path.join(OUT,'walk-jobs.json'))),runJobs=JSON.parse(fs.readFileSync(path.join(OUT,'run-jobs.json')));
 const runtime={},manifest={generator:'built-in image_gen',identities:{}};
 fs.mkdirSync(path.join(OUT,'sheets'),{recursive:true});
 for(const job of jobs){
  const identity=job.identity,[id,form]=IDENTITIES[identity];
  const sheet=path.join(OUT,'sheets',identity+'-run-v3.png'),walkSheet=path.join(OUT,'sheets',identity+'-walk.png');
  if(!fs.existsSync(sheet))fs.copyFileSync(runJobs.find(j=>j.identity===identity).path,sheet);
  if(!fs.existsSync(walkSheet))fs.copyFileSync(walkJobs.find(j=>j.identity===identity).path,walkSheet);
  const runCells=await slice(sheet,2),walkCells=await slice(walkSheet,2);
  runtime[id]||={};manifest.identities[identity]={};
  for(const [name,cells]of [['walk',walkCells],['run',runCells]]){
   const a=context.characters[id].anims[name],ref=await sharp(files(a,form)[0]).ensureAlpha().raw().toBuffer({resolveWithObject:true}),anchor=metrics(ref.data,ref.info.width,ref.info.height);
   const refHead=headX({data:ref.data,width:ref.info.width,m:anchor});
   // One scale per cycle, horizontal head anchor and a shared planted-foot baseline.
   const maxHeight=Math.max(...cells.map(c=>c.m.height)),maxWidth=Math.max(...cells.map(c=>c.m.right-c.m.left+1));
   const scale=Math.min(anchor.height/maxHeight,(ref.info.width-12)/maxWidth);
   const folder=name==='run'?'run-v3':name,out=path.join(OUT,identity,folder);fs.mkdirSync(out,{recursive:true});
   for(let i=0;i<cells.length;i++){
    const c=cells[i],m=c.m,w=Math.round((m.right-m.left+1)*scale),h=Math.round((m.bottom-m.top+1)*scale);
    const resized=await sharp(c.data,{raw:{width:c.width,height:c.height,channels:4}}).extract({left:m.left,top:m.top,width:m.right-m.left+1,height:m.bottom-m.top+1}).resize(w,h,{kernel:'nearest'}).png().toBuffer();
    const flight=name==='run'?[0,0,2,4,0,0,2,4,0,0][i]*anchor.height*.012:0;
    const left=Math.max(0,Math.min(ref.info.width-w,Math.round(refHead-(headX(c)-m.left)*scale)));
    const top=Math.max(0,Math.min(ref.info.height-h,Math.round(anchor.feet-flight-(m.feet-m.top)*scale)));
    await sharp({create:{width:ref.info.width,height:ref.info.height,channels:4,background:'#00000000'}}).composite([{input:resized,left,top}]).png().toFile(path.join(out,String(i).padStart(2,'0')+'.png'));
   }
   runtime[id][name]={...a,frames:10,path:`assets/chars/gait-v2/${form?'{form}':identity}/${folder}`,fps:name==='run'?32:24,loop:true,gaitCycle:true};
   manifest.identities[identity][name]={frames:10,fps:name==='run'?32:24,scale,source:`sheets/${identity}-${name==='run'?'run-v3':'walk'}.png`,cells:cells.map(c=>({row:c.row,column:c.column}))};
  }
  runtime[id].walkBack={...runtime[id].walk,path:runtime[id].walk.path.replace('/walk','/walkBack')};
  const back=path.join(OUT,identity,'walkBack');fs.mkdirSync(back,{recursive:true});
  for(let i=0;i<10;i++)fs.copyFileSync(path.join(OUT,identity,'walk',String((10-i)%10).padStart(2,'0')+'.png'),path.join(back,String(i).padStart(2,'0')+'.png'));
  console.log(identity+': installed walk, run and reversed backstep');
 }
 fs.writeFileSync(path.join(ROOT,'js/gait-v2.js'),`// Generated by tools/build-gait-v2.cjs; prompts and provenance in assets/chars/gait-v2/.\n(()=>{const gaits=${JSON.stringify(runtime,null,2)};for(const id of CONFIG.roster){const a=CONFIG.characters[id].anims;Object.assign(a,gaits[id]);if(a.idle)Object.assign(a.idle,{frames:1,fps:1,loop:false});for(const k of ['charge','uCharge'])if(a[k])Object.assign(a[k],{loop:false,fps:12});}})();\n`);
 fs.writeFileSync(path.join(OUT,'manifest.json'),JSON.stringify(manifest,null,2));
}
main().catch(e=>{console.error(e);process.exitCode=1;});
